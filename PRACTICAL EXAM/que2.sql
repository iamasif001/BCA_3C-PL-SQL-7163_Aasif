SET SERVEROUTPUT ON;

CREATE OR REPLACE FUNCTION GET_GRADE(
    P_PERCENTAGE NUMBER
)
RETURN VARCHAR2
IS
    V_GRADE VARCHAR2(10);
BEGIN
    IF P_PERCENTAGE < 0 OR P_PERCENTAGE > 100 THEN
        V_GRADE := 'INVALID';

    ELSIF P_PERCENTAGE >= 90 THEN
        V_GRADE := 'A';

    ELSIF P_PERCENTAGE >= 75 THEN
        V_GRADE := 'B';

    ELSIF P_PERCENTAGE >= 60 THEN
        V_GRADE := 'C';

    ELSIF P_PERCENTAGE >= 40 THEN
        V_GRADE := 'D';

    ELSE
        V_GRADE := 'FAIL';
    END IF;

    RETURN V_GRADE;
END;
/

DECLARE
    V_PERCENTAGE NUMBER := 85;
    V_GRADE VARCHAR2(10);
BEGIN
    V_GRADE := GET_GRADE(V_PERCENTAGE);

    DBMS_OUTPUT.PUT_LINE('Percentage: ' || V_PERCENTAGE || '%');
    DBMS_OUTPUT.PUT_LINE('Grade: ' || V_GRADE);
END;
/