/*8.  CREATE A TRIGGER THAT STORE THE OLD AND
 NEW SALARY WHENEVER AN EMPLOYEE SALARY IS UPDATED.*/
 
 SET SERVEROUTPUT ON;

CREATE TABLE SALARY_AUDIT
(
    EMPNO NUMBER(4),
    OLD_SALARY NUMBER(7,2),
    NEW_SALARY NUMBER(7,2),
    UPDATE_DATE DATE
);

CREATE OR REPLACE TRIGGER salary_update_trigger
AFTER UPDATE OF SAL ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO SALARY_AUDIT
    VALUES
    (
        :OLD.EMPNO,
        :OLD.SAL,
        :NEW.SAL,
        SYSDATE
    );
END;
/

UPDATE EMP
SET SAL = 25000
WHERE EMPNO = 7369;

SELECT * FROM SALARY_AUDIT;