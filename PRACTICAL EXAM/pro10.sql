/*10. CREATE A SALARY_HISTORY TABLE AND A TRIGGER TO STORE 
EMPLOYEE ID, OLD SALARY, NEW SALARY, AND CHANGE DATE WHENEVER 
SALARY IS UPDATE.*/

SET SERVEROUTPUT ON;

CREATE TABLE SALARY_HISTORY
(
    EMPLOYEE_ID NUMBER(4),
    OLD_SALARY NUMBER(7,2),
    NEW_SALARY NUMBER(7,2),
    CHANGE_DATE DATE
);

CREATE OR REPLACE TRIGGER salary_history_trigger
AFTER UPDATE OF SAL ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO SALARY_HISTORY
    VALUES
    (
        :OLD.EMPNO,
        :OLD.SAL,
        :NEW.SAL,
        SYSDATE
    );
END;
/

UPDATE EMP
SET SAL = 25000
WHERE EMPNO = 7369;

SELECT * FROM SALARY_HISTORY;