/* 11. CRETE A TRIGGER THAR AUTOMATICALLY RECORD THE INSERTION DATE AND USE INFORMATION WHENEVER A NEW EMPLOYEE 
RECORD IS INSERTE.*/

SET SERVEROUTPUT ON;

CREATE TABLE EMP_INSERT_AUDIT
(
    EMPNO NUMBER(4),
    ENAME VARCHAR2(10),
    INSERT_DATE DATE,
    INSERT_USER VARCHAR2(30)
);

CREATE OR REPLACE TRIGGER emp_insert_audit_trigger
AFTER INSERT ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO EMP_INSERT_AUDIT
    VALUES
    (
        :NEW.EMPNO,
        :NEW.ENAME,
        SYSDATE,
        USER
    );
END;
/

