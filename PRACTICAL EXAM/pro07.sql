/*7. CREATE AN EMP-AUDIT TABLE AND A TRIGGER THAT STORES EMPOLYEE
 DETAILS WHENEVER A NEW EMPLOYEE IN INSERTED */
 
 SET SERVEROUTPUT ON;

CREATE TABLE EMP_AUDIT
(
    EMPNO NUMBER(4),
    ENAME VARCHAR2(10),
    JOB VARCHAR2(9),
    SAL NUMBER(7,2),
    DEPTNO NUMBER(2),
    AUDIT_DATE DATE
);

CREATE OR REPLACE TRIGGER emp_audit_trigger
AFTER INSERT ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT
    VALUES
    (
        :NEW.EMPNO,
        :NEW.ENAME,
        :NEW.JOB,
        :NEW.SAL,
        :NEW.DEPTNO,
        SYSDATE
    );
END;
