CREATE TABLE EMPLOYEE_AUDIT (
    EMP_ID NUMBER,
    EMP_NAME VARCHAR2(50),
    SALARY NUMBER(10,2),
    DEPARTMENT VARCHAR2(30),
    DELETED_DATE DATE
);

CREATE OR REPLACE TRIGGER TRG_EMPLOYEE_DELETE
AFTER DELETE ON EMPLOYEE
FOR EACH ROW
BEGIN
    INSERT INTO EMPLOYEE_AUDIT (
        EMP_ID,
        EMP_NAME,
        SALARY,
        DEPARTMENT,
        DELETED_DATE
    )
    VALUES (
        :OLD.EMP_ID,
        :OLD.EMP_NAME,
        :OLD.SALARY,
        :OLD.DEPARTMENT,
        SYSDATE
    );
END;
/

DELETE FROM EMPLOYEE
WHERE EMP_ID = 101;

COMMIT;

