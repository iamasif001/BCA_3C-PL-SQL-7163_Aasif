/*9. CREATE A TRIGGER THAT STORE  DELETED EMPLOYEE INFORMATION 
IN AN AUDIT TABLE.*/

SET SERVEROUTPUT ON;

CREATE TABLE EMP_DELETE_AUDIT
(
    EMPNO NUMBER(4),
    ENAME VARCHAR2(10),
    JOB VARCHAR2(9),
    SAL NUMBER(7,2),
    DEPTNO NUMBER(2),
    DELETE_DATE DATE
);

CREATE OR REPLACE TRIGGER emp_delete_trigger
AFTER DELETE ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO EMP_DELETE_AUDIT
    VALUES
    (
        :OLD.EMPNO,
        :OLD.ENAME,
        :OLD.JOB,
        :OLD.SAL,
        :OLD.DEPTNO,
        SYSDATE
    );
END;
/

DELETE FROM EMP
WHERE EMPNO = 7369;

SELECT * FROM EMP_DELETE_AUDIT;