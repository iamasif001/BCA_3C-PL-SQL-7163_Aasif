/*12. CREATE A TRRIGER THAT KPREVENTS DELETION 
LOD EMPLOYESS BELONGING TO A PARTICULAR DEPARTMENT.*/

SET SERVEROUTPUT ON;

CREATE OR REPLACE TRIGGER prevent_emp_delete
BEFORE DELETE ON EMP
FOR EACH ROW
BEGIN
    IF :OLD.DEPTNO = 10 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Deletion of employees from Department 10 is not allowed');
    END IF;
END;
/

DELETE FROM EMP
WHERE EMPNO = 7839;