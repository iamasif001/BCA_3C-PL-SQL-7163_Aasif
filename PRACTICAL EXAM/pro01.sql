/*1. WRITE A PL SQL THAT ACCEPTS AN EMPLOYEE ID AND 
DISPLAYS AN APPROPTIATE MESSAGE WHEN THE EMPLOYEE 
DOSE NOT EXITS*/

SET SERVEROUTPUT ON;
DECLARE
V_empno EMP.EMP%TYPE;
BEGIN
V_empno := &emp_id;

SELECT empno INTO V_empno
FROM EMP
WHERE EMPNO = V_empno;

DBMS_OUTPUT.PUT_LINE('Empolyee exits');

EXCEPTION
WHEN DATA_NOT_FOUND THEN
DBMS_OUTPUT.PUT_LINE('Employee not exits');
END;
